#!/usr/bin/env node
// Generate the pinned GitHub-slugger scalar and Unicode property tables.
// Usage: node bootstrap/generate-github-slug-data.mjs /path/to/github-slugger/index.js > output.hs
// The input is the unmodified github-slugger 2.0.0 release; no network is used.
import { createHash } from 'node:crypto'
import { readFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const indexPath = process.argv[2] && resolve(process.argv[2])
if (!indexPath || process.version !== 'v22.16.0' || process.versions.unicode !== '16.0') {
  throw new Error('supply github-slugger 2.0.0 index.js and use Node v22.16.0 / Unicode 16.0')
}
for (const [path, expected] of [
  [indexPath, '76082571f2ada4508b1d5ab1267e58c888a5cbc964663221e05830d413d52b14'],
  [join(dirname(indexPath), 'regex.js'), '3bcbb3836a4e76f0f343c34d223ddd9eac83cc73a4e2c7a1118ef0829bc9129b']
]) {
  const actual = createHash('sha256').update(await readFile(path)).digest('hex')
  if (actual !== expected) throw new Error(`unexpected reference hash for ${path}: ${actual}`)
}
const { slug } = await import(pathToFileURL(indexPath).href)
const isCased = /\p{Cased}/u
const isIgnorable = /\p{Case_Ignorable}/u
const removed = [], changes = [], multi = [], cased = [], ignorable = []
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue
  const input = String.fromCodePoint(cp)
  const result = slug(input)
  if (!result) removed.push([cp, 0])
  else if (result !== input) {
    const output = [...result].map(c => c.codePointAt(0))
    if (output.length === 1) changes.push([cp, output[0] - cp])
    else multi.push([cp, output])
  }
  if (isCased.test(input)) cased.push([cp, 0])
  if (isIgnorable.test(input)) ignorable.push([cp, 0])
}
function ranges(items) {
  const result = []
  for (const [point, value] of items) {
    const previous = result.at(-1)
    if (previous && previous[1] + 1 === point && previous[2] === value) previous[1] = point
    else result.push([point, point, value])
  }
  return result
}
const hex = n => n < 0 ? `-0x${(-n).toString(16)}` : `0x${n.toString(16)}`
function table(name, signature, rows, format) {
  const lines = [`${name} :: ${signature}`, `${name} =`, '  IntMap.fromDistinctAscList', '    [ ' + format(rows[0])]
  for (const row of rows.slice(1)) lines.push('    , ' + format(row))
  lines.push('    ]', '')
  return lines.join('\n')
}
const interval = ([start,end]) => `(${hex(start)}, ${hex(end)})`
const change = ([start,end,delta]) => `(${hex(start)}, (${hex(end)}, ${hex(delta)}))`
const expansion = ([cp, values]) => `(${hex(cp)}, Text.pack [${values.map(v => `chr ${hex(v)}`).join(', ')}])`
const header = `{-# LANGUAGE OverloadedStrings #-}\n\n-- Generated by bootstrap/generate-github-slug-data.mjs using github-slugger\n-- 2.0.0 and Node 22.16.0 / Unicode 16.0. Do not edit the tables by hand.\n--\n-- Copyright (c) 2015, Dan Flettre <fletd01@yahoo.com>\n--\n-- Permission to use, copy, modify, and/or distribute this software for any\n-- purpose with or without fee is hereby granted, provided that the above\n-- copyright notice and this permission notice appear in all copies.\n--\n-- THE SOFTWARE IS PROVIDED "AS IS" AND THE AUTHOR DISCLAIMS ALL WARRANTIES\n-- WITH REGARD TO THIS SOFTWARE INCLUDING ALL IMPLIED WARRANTIES OF\n-- MERCHANTABILITY AND FITNESS. IN NO EVENT SHALL THE AUTHOR BE LIABLE FOR\n-- ANY SPECIAL, DIRECT, INDIRECT, OR CONSEQUENTIAL DAMAGES OR ANY DAMAGES\n-- WHATSOEVER RESULTING FROM LOSS OF USE, DATA OR PROFITS, WHETHER IN AN\n-- ACTION OF CONTRACT, NEGLIGENCE OR OTHER TORTIOUS ACTION, ARISING OUT OF OR\n-- IN CONNECTION WITH THE USE OR PERFORMANCE OF THIS SOFTWARE.\n\nmodule JitML.Docs.GithubSlugData\n  ( githubSlugScalar\n  , githubCased\n  , githubCaseIgnorable\n  )\nwhere\n\nimport Data.Char (chr, ord)\nimport Data.IntMap.Strict qualified as IntMap\nimport Data.Text (Text)\nimport Data.Text qualified as Text\n\n-- Tables include every Unicode scalar; callers handle contextual final sigma.\ngithubSlugScalar :: Char -> Text\ngithubSlugScalar character\n  | inRanges removedRanges point = ""\n  | Just expanded <- IntMap.lookup point expansions = expanded\n  | Just (start, (end, delta)) <- IntMap.lookupLE point changes\n  , start <= point && point <= end =\n      Text.singleton (chr (point + delta))\n  | otherwise = Text.singleton character\n where\n  point = ord character\n\ngithubCased :: Char -> Bool\ngithubCased = inRanges casedRanges . ord\n\ngithubCaseIgnorable :: Char -> Bool\ngithubCaseIgnorable = inRanges ignorableRanges . ord\n\ninRanges :: IntMap.IntMap Int -> Int -> Bool\ninRanges ranges point =\n  case IntMap.lookupLE point ranges of\n    Just (start, end) -> start <= point && point <= end\n    Nothing -> False\n\n`
process.stdout.write(header)
process.stdout.write(table('removedRanges','IntMap.IntMap Int',ranges(removed),interval))
process.stdout.write(table('changes','IntMap.IntMap (Int, Int)',ranges(changes),change))
process.stdout.write(table('expansions','IntMap.IntMap Text',multi,expansion))
process.stdout.write(table('casedRanges','IntMap.IntMap Int',ranges(cased),interval))
process.stdout.write(table('ignorableRanges','IntMap.IntMap Int',ranges(ignorable),interval))

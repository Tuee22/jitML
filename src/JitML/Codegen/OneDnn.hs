    , "    const float *weights, std::size_t weights_count) {"
    , "  if (n == 0) { return; }"
    , "  std::size_t block = n * n;"
    , "  std::vector<float> Wq(block, 0.0f), Wk(block, 0.0f), Wv(block, 0.0f);"
    , "  for (std::size_t i = 0; i < block && i < weights_count; ++i) { Wq[i] = weights[i]; }"
    , "  for (std::size_t i = 0; i < block && (block + i) < weights_count; ++i) { Wk[i] = weights[block + i]; }"
    , "  for (std::size_t i = 0; i < block && (2 * block + i) < weights_count; ++i) { Wv[i] = weights[2 * block + i]; }"
    , "  std::vector<float> q(n, 0.0f), k(n, 0.0f), kq(n, 0.0f);"
    , "  for (std::size_t i = 0; i < n; ++i) {"
    , "    float qsum = 0.0f, ksum = 0.0f;"
    , "    for (std::size_t j = 0; j < n; ++j) {"
    , "      qsum += input[j] * Wq[j * n + i];"
    , "      ksum += input[j] * Wk[j * n + i];"
    , "    }"
    , "    q[i] = qsum;"
    , "    k[i] = ksum;"
    , "  }"
    , "  for (std::size_t i = 0; i < n; ++i) {"
    , "    float v = 0.0f;"
    , "    for (std::size_t j = 0; j < n; ++j) { v += q[j] * k[j] * Wv[j * n + i]; }"
    , "    out[i] = v;"
    , "  }"
    , "  (void)kq;"
    , "}"

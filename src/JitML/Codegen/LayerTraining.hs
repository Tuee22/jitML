{-# LANGUAGE OverloadedStrings #-}

-- | The backend-agnostic operator layer of the generated layer-graph training
-- kernel.
--
-- Sprint `264.1`. Every substrate that trains the typed 'JitML.Numerics.LayerGraph'
-- IR renders the same operator bodies — the affine/kind dispatch, the correct
-- operators (GeGLU, normalization, patch-embed, multi-head attention, residual),
-- and the unified `jitml_op_train` opcode entry. They are shared text rather than
-- a per-lane copy because the operators are compositions: each one calls into the
-- /primitive layer/ its backend supplies (matmul, convolution, pooling, scale) and
-- otherwise does elementwise and reduction glue that has no backend-specific form.
-- A divergence between two lanes' operator semantics therefore requires editing
-- one string, which is the point.
--
-- The primitive-layer contract — the names this text may call, which every
-- backend renderer must define before splicing it — is:
--
-- * @jitml_matmul_{forward,backward_data,backward_weights}@
-- * @jitml_conv2d_{forward,backward_data,backward_weights}@ (flat)
-- * @jitml_conv3d_{forward,backward_data,backward_weights}@ (flat)
-- * @jitml_pool_train@, @jitml_scale_train@
-- * @{forward,backward_data,backward_weights}_primitive_name@
-- * the @JITML_LAYER_{DENSE,CONV2D,CONV3D}@ kind codes
module JitML.Codegen.LayerTraining
  ( layerTrainingOperatorLayer
  , layerTrainingKindDispatchLayer
  , layerTrainingOperatorBodies
  , layerTrainingOpTrainEntry
  )
where

import Data.Text (Text)

-- | The shared operator layer as one contiguous block, for a backend whose
-- emission order is free to be chosen.  A backend that must preserve an
-- existing byte-for-byte emission order splices the three chunks below at its
-- own offsets instead; Sprint `263.1` pinned the `linux-cpu` artifact digest
-- into the committed lane fragment, so `linux-cpu` is such a backend.
layerTrainingOperatorLayer :: [Text]
layerTrainingOperatorLayer =
  layerTrainingKindDispatchLayer
    <> ("" : layerTrainingOperatorBodies)
    <> ("" : layerTrainingOpTrainEntry)

-- | Chunk A: the primitive-name accessors and the layer-kind dispatch that
-- routes an affine layer to its backend's matmul or convolution primitive.
layerTrainingKindDispatchLayer :: [Text]
layerTrainingKindDispatchLayer =
  [ "extern \"C\" const char *jitml_layer_forward_primitive(int kind) {"
  , "  return forward_primitive_name(kind);"
  , "}"
  , ""
  , "extern \"C\" const char *jitml_layer_backward_data_primitive(int kind) {"
  , "  return backward_data_primitive_name(kind);"
  , "}"
  , ""
  , "extern \"C\" const char *jitml_layer_backward_weights_primitive(int kind) {"
  , "  return backward_weights_primitive_name(kind);"
  , "}"
  , ""
  , "extern \"C\" void jitml_layer_forward("
  , "    float *out, const float *input, const float *weights, const float *bias,"
  , "    int inputs, int outputs, int kind, int batch) {"
  , "  if (kind == JITML_LAYER_CONV2D) {"
  , "    jitml_conv2d_forward(out, input, weights, bias, inputs, outputs, batch);"
  , "    return;"
  , "  }"
  , "  if (kind == JITML_LAYER_CONV3D) {"
  , "    jitml_conv3d_forward(out, input, weights, bias, inputs, outputs, batch);"
  , "    return;"
  , "  }"
  , "  jitml_matmul_forward(out, input, weights, bias, inputs, outputs, batch);"
  , "}"
  , ""
  , "extern \"C\" void jitml_layer_backward_data("
  , "    float *dx, const float *d_pre, const float *weights,"
  , "    int inputs, int outputs, int kind, int batch) {"
  , "  if (kind == JITML_LAYER_CONV2D) {"
  , "    jitml_conv2d_backward_data(dx, d_pre, weights, inputs, outputs, batch);"
  , "    return;"
  , "  }"
  , "  if (kind == JITML_LAYER_CONV3D) {"
  , "    jitml_conv3d_backward_data(dx, d_pre, weights, inputs, outputs, batch);"
  , "    return;"
  , "  }"
  , "  jitml_matmul_backward_data(dx, d_pre, weights, inputs, outputs, batch);"
  , "}"
  , ""
  , "extern \"C\" void jitml_layer_backward_weights("
  , "    float *g_weights, float *g_bias, const float *d_pre, const float *input,"
  , "    int inputs, int outputs, int kind, int batch) {"
  , "  if (kind == JITML_LAYER_CONV2D) {"
  , "    jitml_conv2d_backward_weights(g_weights, g_bias, d_pre, input, inputs, outputs, batch);"
  , "    return;"
  , "  }"
  , "  if (kind == JITML_LAYER_CONV3D) {"
  , "    jitml_conv3d_backward_weights(g_weights, g_bias, d_pre, input, inputs, outputs, batch);"
  , "    return;"
  , "  }"
  , "  jitml_matmul_backward_weights(g_weights, g_bias, d_pre, input, inputs, outputs, batch);"
  , "}"
  ]

-- | Chunk B: the correct-operator bodies (GELU, GeGLU, normalization, patch
-- embedding, multi-head attention, residual) that every substrate shares.
layerTrainingOperatorBodies :: [Text]
layerTrainingOperatorBodies =
  [ "// Phase 241 correct-operator device training kernels. Each renders the"
  , "// operator's real forward + backward-data + backward-weights, reusing the"
  , "// proven oneDNN matmul primitives (jitml_matmul_forward / _backward_data /"
  , "// _backward_weights) for every affine/projection sub-op and plain device C++"
  , "// for the elementwise (GELU), reduction (normalization statistics, softmax),"
  , "// and gather/scatter (patch) glue. Layouts match the pure LayerGraph oracle"
  , "// exactly (row-major W[out,in]; packed weight/bias segment order per"

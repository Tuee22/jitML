  , "  for (int hd = 0; hd < heads; ++hd) {"
  , "    for (int i = 0; i < sN; ++i) {"
  , "      std::vector<float> sco(sN);"
  , "      float mx = -INFINITY;"
  , "      for (int t = 0; t < sN; ++t) {"
  , "        float v;"
  , "        if (causal != 0 && t > i) { v = -INFINITY; }"
  , "        else {"
  , "          float dot = 0.0f;"
  , "          for (int e = 0; e < dh; ++e) { dot += qs[static_cast<std::size_t>(i) * dModel + hd * dh + e] * ks[static_cast<std::size_t>(t) * dModel + hd * dh + e]; }"

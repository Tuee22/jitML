  , "  std::vector<int> idxs(cpp);"
  , "  int patchIdx = 0;"
  , "  for (int yi = 0; yi < nY; ++yi) {"
  , "    for (int xi = 0; xi < nX; ++xi) {"
  , "      int y0 = yi * stride;"
  , "      int x0 = xi * stride;"
  , "      int k = 0;"
  , "      for (int dyp = 0; dyp < cP; ++dyp) {"
  , "        for (int dxp = 0; dxp < cP; ++dxp) {"
  , "          for (int c = 0; c < cC; ++c) {"

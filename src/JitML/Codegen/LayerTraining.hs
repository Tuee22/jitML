  , "// backwardLayerGraph within float32 tolerance. Single example (batch=1); the"
  , "// Haskell batched path folds per example."
  , "static inline float jitml_gelu(float u) {"
  , "  return 0.5f * u * (1.0f + std::erf(u * 0.7071067811865476f));"
  , "}"
  , "static inline float jitml_gelu_deriv(float u) {"
  , "  return 0.5f * (1.0f + std::erf(u * 0.7071067811865476f))"
  , "       + u * std::exp(-0.5f * u * u) * 0.3989422804014327f;"
  , "}"
  , "static inline float jitml_act_fwd(int code, float z) {"
  , "  if (code == 1) { return std::tanh(z); }"
  , "  if (code == 2) { return z > 0.0f ? z : 0.0f; }"
  , "  return z;"
  , "}"
  , "static inline float jitml_act_bwd(int code, float activated, float up) {"
  , "  if (code == 1) { return (1.0f - activated * activated) * up; }"
  , "  if (code == 2) { return activated > 0.0f ? up : 0.0f; }"
  , "  return up;"
  , "}"
  , ""
  , "// GeGLU: a = Wa x + ba; g = Wb x + bb; h = a * gelu(g); y = W2 h + b2."
  , "static void jitml_geglu_train("
  , "    float *out, float *dx, float *dw, float *db,"
  , "    const float *x, const float *weights, const float *bias, const float *dy,"
  , "    int gin, int gff, int gout) {"
  , "  const float *wa = weights;"
  , "  const float *wb = weights + static_cast<std::size_t>(gff) * gin;"
  , "  const float *w2 = weights + 2 * static_cast<std::size_t>(gff) * gin;"
  , "  const float *ba = bias;"
  , "  const float *bb = bias + gff;"
  , "  const float *b2 = bias + 2 * gff;"
  , "  std::vector<float> a(gff), g(gff), gg(gff), hbuf(gff);"
  , "  jitml_matmul_forward(a.data(), x, wa, ba, gin, gff, 1);"
  , "  jitml_matmul_forward(g.data(), x, wb, bb, gin, gff, 1);"
  , "  for (int i = 0; i < gff; ++i) { gg[i] = jitml_gelu(g[i]); hbuf[i] = a[i] * gg[i]; }"
  , "  jitml_matmul_forward(out, hbuf.data(), w2, b2, gff, gout, 1);"
  , "  float *dwa = dw;"
  , "  float *dwb = dw + static_cast<std::size_t>(gff) * gin;"
  , "  float *dw2 = dw + 2 * static_cast<std::size_t>(gff) * gin;"
  , "  float *dba = db;"
  , "  float *dbb = db + gff;"
  , "  float *db2 = db + 2 * gff;"
  , "  jitml_matmul_backward_weights(dw2, db2, dy, hbuf.data(), gff, gout, 1);"
  , "  std::vector<float> dh(gff);"
  , "  jitml_matmul_backward_data(dh.data(), dy, w2, gff, gout, 1);"
  , "  std::vector<float> da(gff), dg(gff);"
  , "  for (int i = 0; i < gff; ++i) {"
  , "    da[i] = dh[i] * gg[i];"
  , "    dg[i] = dh[i] * a[i] * jitml_gelu_deriv(g[i]);"
  , "  }"
  , "  jitml_matmul_backward_weights(dwa, dba, da.data(), x, gin, gff, 1);"
  , "  jitml_matmul_backward_weights(dwb, dbb, dg.data(), x, gin, gff, 1);"
  , "  std::vector<float> dxa(gin), dxb(gin);"
  , "  jitml_matmul_backward_data(dxa.data(), da.data(), wa, gin, gff, 1);"
  , "  jitml_matmul_backward_data(dxb.data(), dg.data(), wb, gin, gff, 1);"
  , "  for (int i = 0; i < gin; ++i) { dx[i] = dxa[i] + dxb[i]; }"
  , "}"
  , ""
  , "// Normalization (batch / layer / group). flavor: 0=batch, 1=layerwise,"
  , "// 2=group. gamma=weights, beta=bias (length channels). Mirrors the oracle's"
  , "// biased (divide-by-m) variance and per-group reduction exactly."
  , "static void jitml_norm_train("
  , "    float *out, float *dx, float *dw, float *db,"
  , "    const float *x, const float *gamma, const float *beta, const float *dy,"
  , "    int flavor, int channels, int spatial, int groups, float eps, int len) {"
  , "  std::vector<int> groupOf(len, 0);"
  , "  int numGroups = 1;"
  , "  if (flavor == 1) { numGroups = 1; for (int i = 0; i < len; ++i) { groupOf[i] = 0; } }"
  , "  else if (flavor == 2) {"
  , "    int gsz = groups > 0 ? channels / groups : channels;"
  , "    if (gsz <= 0) { gsz = 1; }"
  , "    numGroups = groups > 0 ? groups : 1;"
  , "    for (int i = 0; i < len; ++i) { groupOf[i] = (i / spatial) / gsz; }"
  , "  } else {"
  , "    numGroups = channels;"
  , "    for (int i = 0; i < len; ++i) { groupOf[i] = i % channels; }"
  , "  }"
  , "  std::vector<float> mu(numGroups, 0.0f), var(numGroups, 0.0f), rstd(numGroups, 0.0f);"
  , "  std::vector<int> cnt(numGroups, 0);"
  , "  for (int i = 0; i < len; ++i) { mu[groupOf[i]] += x[i]; cnt[groupOf[i]] += 1; }"
  , "  for (int gi = 0; gi < numGroups; ++gi) { if (cnt[gi] > 0) { mu[gi] /= static_cast<float>(cnt[gi]); } }"
  , "  for (int i = 0; i < len; ++i) { float d = x[i] - mu[groupOf[i]]; var[groupOf[i]] += d * d; }"
  , "  for (int gi = 0; gi < numGroups; ++gi) {"
  , "    if (cnt[gi] > 0) { var[gi] /= static_cast<float>(cnt[gi]); }"
  , "    rstd[gi] = 1.0f / std::sqrt(var[gi] + eps);"
  , "  }"
  , "  std::vector<float> xhat(len);"
  , "  for (int i = 0; i < len; ++i) { int gi = groupOf[i]; xhat[i] = (x[i] - mu[gi]) * rstd[gi]; }"
  , "  for (int i = 0; i < len; ++i) {"
  , "    int c = flavor == 0 ? (i % channels) : (i / spatial);"
  , "    out[i] = gamma[c] * xhat[i] + beta[c];"
  , "  }"
  , "  std::vector<float> ghat(len);"
  , "  for (int i = 0; i < len; ++i) {"
  , "    int c = flavor == 0 ? (i % channels) : (i / spatial);"
  , "    ghat[i] = dy[i] * gamma[c];"
  , "  }"
  , "  std::vector<float> meanG(numGroups, 0.0f), meanGX(numGroups, 0.0f);"
  , "  for (int i = 0; i < len; ++i) { int gi = groupOf[i]; meanG[gi] += ghat[i]; meanGX[gi] += ghat[i] * xhat[i]; }"
  , "  for (int gi = 0; gi < numGroups; ++gi) {"
  , "    if (cnt[gi] > 0) { meanG[gi] /= static_cast<float>(cnt[gi]); meanGX[gi] /= static_cast<float>(cnt[gi]); }"
  , "  }"
  , "  for (int i = 0; i < len; ++i) {"
  , "    int gi = groupOf[i];"
  , "    dx[i] = rstd[gi] * (ghat[i] - meanG[gi] - xhat[i] * meanGX[gi]);"
  , "  }"
  , "  for (int c = 0; c < channels; ++c) { dw[c] = 0.0f; db[c] = 0.0f; }"
  , "  for (int i = 0; i < len; ++i) {"
  , "    int c = flavor == 0 ? (i % channels) : (i / spatial);"
  , "    dw[c] += dy[i] * xhat[i];"
  , "    db[c] += dy[i];"
  , "  }"
  , "}"
  , ""
  , "// Patch embedding: gather each P*P*C patch (pixel-row-major idx ="
  , "// ((y*W)+x)*C+c), project e = W p + b (cpp -> D), scatter dp back to dX."
